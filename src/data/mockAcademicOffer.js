export const parseCourseDivision = (course) => {
  if (!course) return { nombre: '', division: '' };
  if (course.division) {
    return {
      nombre: course.nombre,
      division: course.division,
    };
  }
  const match = course.nombre?.match(/^(.*?)(?:\s*-\s*División|\s*)?"([^"]+)"$/i);
  if (match) {
    return {
      nombre: match[1].trim(),
      division: match[2].trim(),
    };
  }
  return {
    nombre: course.nombre || 'Curso',
    division: 'A',
  };
};
